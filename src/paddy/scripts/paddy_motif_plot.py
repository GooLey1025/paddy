def main():
    """Main function to run the plotting script."""
    parser = argparse.ArgumentParser(description='Create tissue-specific motif plots with PWM logos and saliency distributions')
    
    parser.add_argument('-i', '--input', required=True,
                       help='Input H5 file from motif_metadata_summary.py')
    parser.add_argument('-o', '--output_dir', default='plots',
                       help='Output directory for plots')
    parser.add_argument('-t', '--tissue_id', type=int, default=None,
                       help='Target tissue ID (if None, plot all tissues)')
    parser.add_argument('-m', '--max_motifs', type=int, default=10,
                       help='Maximum number of motifs per tissue')
    parser.add_argument('-f', '--format', choices=['png', 'jpg', 'jpeg', 'pdf', 'svg'], default='png',
                       help='Output image format (default: png)')
    parser.add_argument('-g', '--grads_dir', default=None,
                       help='Directory containing grads H5 files (e.g., 5tissues_grads/) to recompute saliency')
    parser.add_argument('--y-min', type=float, default=-0.001,
                       help='Minimum Y-axis value for saliency plots (default: -0.001)')
    parser.add_argument('--y-max', type=float, default=0.0001,
                       help='Maximum Y-axis value for saliency plots (default: 0.0001)')
    
